export function journeyMarkdown(value, discussions, sources){
  const references=ids=>ids?.length?`相关来源：${ids.map(id=>{const source=sources.find(s=>s.id===id);if(!source)throw new Error(`缺少来源 ${id}`);return `[${id} ${source.title}](${source.url})`;}).join('；')}`:'';
  const cell=value=>String(value).replaceAll('|','\\|').replaceAll('\n','<br>');
  const sections=[`# 010 · 从 Atypica 到 AI 社区：理解演进与扩展记录`,`整理日期：${value.updated_at}。这是讨论的完整主题整理，不是逐字聊天转录。原实验保持停止；产品与流程的扩展功能未实现或验证，已有规格及历史回顾样例分别标记。`,value.lead,'## 当前理解',...value.principles.map(p=>`### ${p.title}\n\n${p.text}`)];
  for(const chapter of value.chapters){
    sections.push(`## ${chapter.title}`,`状态：${chapter.status}`,chapter.lead);
    for(const block of chapter.sections){
      sections.push(`### ${block.heading}`,...block.paragraphs||[]);
      if(block.table)sections.push([`| ${block.table.headers.map(cell).join(' | ')} |`,`| ${block.table.headers.map(()=>'---').join(' | ')} |`,...block.table.rows.map(row=>`| ${row.map(cell).join(' | ')} |`)].join('\n'));
      if(block.items)sections.push(block.items.map(item=>`- ${item}`).join('\n'));
      if(block.note)sections.push(`说明：${block.note}`);
      const refs=references(block.refs);if(refs)sections.push(refs);
    }
  }
  sections.push('## 按提问顺序整理的完整问题库');
  for(const q of discussions)sections.push(`### ${q.question}`,`类型：${q.tag}`,q.paragraphs.join('\n\n'),references(q.refs));
  return sections.filter(Boolean).join('\n\n')+'\n';
}
