const $ = selector => document.querySelector(selector);
const query = new URLSearchParams(location.search);
let language = query.get('lang') === 'en' ? 'en' : 'zh';
let theme = 'light';
try { theme = localStorage.getItem('research-001-theme') === 'dark' ? 'dark' : 'light'; } catch {}
let project, selected = 'input', activePanel = 'map';
const frame = $('#diagram');
const sourceUrl = source => `${project.repository}/blob/${project.revision}/${source.path}#L${source.line}-L${source.end_line}`;

function applyTheme() {
  document.documentElement.dataset.theme = theme;
  const label = language === 'en' ? `Switch to ${theme === 'light' ? 'dark' : 'light'} theme` : `切换为${theme === 'light' ? '深' : '浅'}色主题`;
  $('#theme').setAttribute('aria-label', label);
  $('#theme').title = label;
  try { localStorage.setItem('research-001-theme', theme); localStorage.setItem('archify-theme', theme); } catch {}
  if (frame.contentDocument?.documentElement.dataset.theme && frame.contentDocument.documentElement.dataset.theme !== theme) {
    frame.contentDocument.getElementById('btn-theme')?.click();
  }
}

function setPanel(panel) {
  activePanel = panel;
  for (const button of document.querySelectorAll('[data-panel]')) {
    const active = button.dataset.panel === panel;
    button.classList.toggle('active', active);
    button.setAttribute('aria-selected', String(active));
    button.tabIndex = active ? 0 : -1;
    $(`#panel-${button.dataset.panel}`).hidden = !active;
  }
}

function selectNode(id, focus = true) {
  selected = id;
  const i = language === 'en' ? 1 : 0;
  const node = project.nodes.find(n => n.id === id);
  $('#detail-title').textContent = node.label[i];
  $('#detail-copy').textContent = node.description[i];
  $('#detail-source').href = sourceUrl(node.source);
  $('#step-count').textContent = `${String(project.nodes.indexOf(node) + 1).padStart(2, '0')} / 08`;
  for (const button of document.querySelectorAll('.node-button')) {
    const active = button.dataset.node === id;
    button.classList.toggle('selected', active);
    button.setAttribute('aria-pressed', String(active));
  }
  if (focus) { setPanel('map'); frame.contentWindow.location.hash = `focus=${id}`; }
}

function buildLists() {
  const i = language === 'en' ? 1 : 0;
  $('#node-nav').replaceChildren(); $('#flow-list').replaceChildren(); $('#source-rows').replaceChildren();
  project.nodes.forEach((node, index) => {
    const button = document.createElement('button');
    button.type = 'button'; button.className = 'node-button'; button.dataset.node = node.id;
    button.innerHTML = `<span class="node-number">${String(index + 1).padStart(2, '0')}</span><span>${node.label[i]}</span><span class="node-arrow" aria-hidden="true">↗</span>`;
    button.addEventListener('click', () => selectNode(node.id)); $('#node-nav').append(button);
    const step = document.createElement('li');
    step.innerHTML = `<span class="flow-number">${String(index + 1).padStart(2, '0')}</span><div><h3>${node.label[i]}</h3><p>${node.description[i]}</p><button class="text-link" type="button">${strings[language].inspect} ↗</button></div>`;
    step.querySelector('button').addEventListener('click', () => { selectNode(node.id); $('#explore').scrollIntoView({ behavior: 'smooth' }); });
    $('#flow-list').append(step);
    const row = document.createElement('tr');
    row.innerHTML = `<td>${node.label[i]}</td><td>${node.source.path}</td><td>${node.source.line}–${node.source.end_line}</td><td><a href="${sourceUrl(node.source)}" target="_blank" rel="noreferrer" aria-label="${strings[language].viewSource}: ${node.label[i]}">${strings[language].open}</a></td>`;
    $('#source-rows').append(row);
  });
  selectNode(selected, false);
}

function renderLanguage(reload = true) {
  const readingState = frame.contentWindow?.location.hash || '';
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
  document.title = language === 'en' ? '001 · Archify repository guide' : '001 · Archify 项目导览';
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = strings[language][el.dataset.i18n];
  $('#language').innerHTML = `${language === 'en' ? '中文' : 'EN'} <span aria-hidden="true">↗</span>`;
  $('#language').setAttribute('aria-label', language === 'en' ? '切换为中文' : 'Switch to English');
  $('.tabs').setAttribute('aria-label', language === 'en' ? 'Repository guide' : '项目导览');
  $('.inspector').setAttribute('aria-label', language === 'en' ? 'Component notes' : '组件讲解');
  frame.title = language === 'en' ? 'Archify interactive architecture' : 'Archify 交互式结构图';
  const diagramPath = `./diagrams/archify-${language}.html`;
  $('#open-diagram').href = diagramPath;
  $('#download-html').href = diagramPath;
  $('#download-json').href = `./diagrams/archify-${language}.json`;
  applyTheme();
  if (project) buildLists();
  if (reload) {
    $('#frame-loading').hidden = false;
    frame.src = `${diagramPath}?theme=${theme}${readingState}`;
  }
}

function tracePath() {
  setPanel('map');
  frame.contentWindow.location.hash = 'route=input~export';
  $('#explore').scrollIntoView({ behavior: 'smooth' });
}

$('#theme').addEventListener('click', () => { theme = theme === 'light' ? 'dark' : 'light'; applyTheme(); });
$('#language').addEventListener('click', () => {
  language = language === 'en' ? 'zh' : 'en';
  const url = new URL(location.href); url.searchParams.set('lang', language);
  history.replaceState(null, '', url); renderLanguage();
});
for (const button of document.querySelectorAll('[data-panel]')) button.addEventListener('click', () => setPanel(button.dataset.panel));
$('.tabs').addEventListener('keydown', event => {
  if (!['ArrowLeft','ArrowRight','Home','End'].includes(event.key)) return;
  event.preventDefault();
  const tabs = [...document.querySelectorAll('[data-panel]')];
  const current = tabs.findIndex(t => t.dataset.panel === activePanel);
  const next = event.key === 'Home' ? 0 : event.key === 'End' ? tabs.length - 1 : (current + (event.key === 'ArrowRight' ? 1 : -1) + tabs.length) % tabs.length;
  setPanel(tabs[next].dataset.panel); tabs[next].focus();
});
$('#trace').addEventListener('click', tracePath); $('#flow-trace').addEventListener('click', tracePath);
frame.addEventListener('load', () => {
  $('#frame-loading').hidden = true;
  applyTheme();
  // Keep the host notes and theme aligned with native reader interactions.
  const doc = frame.contentDocument;
  if (!doc) return;
  doc.addEventListener('click', event => {
    const target = event.target.closest('[data-node-id]');
    if (target && project.nodes.some(n => n.id === target.dataset.nodeId)) selectNode(target.dataset.nodeId, false);
  });
  const observer = new MutationObserver(() => {
    const native = doc.documentElement.dataset.theme;
    if (native && native !== theme) { theme = native; applyTheme(); }
  });
  observer.observe(doc.documentElement, { attributes: true, attributeFilter: ['data-theme'] });
});

try {
  const response = await fetch('./project.json');
  if (!response.ok) throw new Error(`Project data: HTTP ${response.status}`);
  project = await response.json(); renderLanguage();
} catch (error) {
  const message = $('#app-error'); message.hidden = false;
  message.textContent = `页面资源加载失败，请通过本地预览服务打开。${error.message}`;
  $('#frame-loading').hidden = true;
}
