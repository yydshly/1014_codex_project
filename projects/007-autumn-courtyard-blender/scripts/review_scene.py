"""Reopen the saved .blend, inspect it, and render a second, elevated camera.

This checks the delivered project, not just the original generation process.
Run: blender -b artifacts/autumn-courtyard.blend --python scripts/review_scene.py
"""
import json
import math
import sys
import time
from pathlib import Path
from types import SimpleNamespace

import bpy
from mathutils import Vector

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(Path(__file__).resolve().parent))
from build_scene import render_setup


scene=bpy.context.scene
assert Path(bpy.data.filepath).name=="autumn-courtyard.blend", "Open the saved scene before reviewing"
mesh_objects=[o for o in scene.objects if o.type=="MESH"]
non_finite=[]
inverted_boxes=[]
for obj in mesh_objects:
    if any(not math.isfinite(c) for v in obj.data.vertices for c in v.co):
        non_finite.append(obj.name)
    # Cuboids generated by box() are closed: their signed volume must be positive.
    if len(obj.data.vertices)==8 and len(obj.data.polygons)==6:
        volume=0
        for p in obj.data.polygons:
            points=[obj.data.vertices[i].co for i in p.vertices]
            for i in range(1,len(points)-1):
                volume+=points[0].dot(points[i].cross(points[i+1]))/6
        if volume<=0:inverted_boxes.append(obj.name)
report={"saved_blend":str(Path(bpy.data.filepath).relative_to(ROOT)),"blender":bpy.app.version_string,
        "objects":len(scene.objects),"meshes":len(mesh_objects),"materials":len(bpy.data.materials),
        "external_image_files":[i.filepath for i in bpy.data.images if i.source=="FILE"],
        "non_finite_meshes":non_finite,"inverted_cuboids":inverted_boxes,
        "asset_counts":json.loads(scene.get("asset_counts_json","{}")),
        "camera_animation_frames":[scene.frame_start,scene.frame_end],
        "reference_is_background_image":bool(scene.camera.data.background_images),
        "checks_passed":not non_finite and not inverted_boxes and bool(scene.camera)}
assert report["checks_passed"],json.dumps(report)
report["device"],report["devices"]=render_setup(SimpleNamespace(quality="final",device="auto"))
c=scene.camera
c.animation_data_clear()
c.location=(34,-25,30)
c.rotation_euler=(Vector((0,21,8))-c.location).to_track_quat("-Z","Y").to_euler()
c.data.lens=31;c.data.dof.use_dof=False
scene.render.resolution_x=1280;scene.render.resolution_y=900
scene.cycles.samples=64
scene.render.filepath=str(ROOT/"assets"/"overview.png")
started=time.perf_counter()
bpy.ops.render.render(write_still=True)
report["overview_render_seconds"]=round(time.perf_counter()-started,2)
(ROOT/"assets"/"scene-checks.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
print("REVIEW",json.dumps(report),flush=True)
